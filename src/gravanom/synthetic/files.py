"""Write the synthetic dataset files (§8.2 outputs)."""

from __future__ import annotations

from pathlib import Path

from gravanom.io.writers import write_cog, write_csv, write_json
from gravanom.synthetic.generator import SYNTHETIC_LABEL, SyntheticSurvey


def write_synthetic(survey: SyntheticSurvey, out_dir: str | Path) -> dict[str, Path]:
    """Write ``synthetic_survey.csv``, ``synthetic_truth_cba_500m.tif`` and ``synthetic_metadata.json``."""
    out = Path(out_dir)
    paths = {
        "survey": write_csv(
            survey.stations,
            out / "synthetic_survey.csv",
            header_comment=f"{SYNTHETIC_LABEL} DATA - fictitious values generated by gravanom; licence CC BY 4.0",
        ),
        "truth": write_cog(
            survey.truth_cba,
            survey.grid_x,
            survey.grid_y,
            out / "synthetic_truth_cba_500m.tif",
            tags={"label": SYNTHETIC_LABEL, "quantity": "true complete Bouguer anomaly", "units": "mGal"},
        ),
        "metadata": write_json(survey.metadata, out / "synthetic_metadata.json"),
    }
    return paths
